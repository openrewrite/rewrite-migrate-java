package org.openrewrite.java.migrate.search;

import lombok.EqualsAndHashCode;
import lombok.Value;
import org.openrewrite.ExecutionContext;
import org.openrewrite.Recipe;
import org.openrewrite.TreeVisitor;
import org.openrewrite.java.JavaIsoVisitor;
import org.openrewrite.java.migrate.internal.GeneratedJavaSource;
import org.openrewrite.java.tree.J;
import org.openrewrite.marker.SearchResult;

@EqualsAndHashCode(callSuper = false)
@Value
public class IsHandwrittenJava extends Recipe {
    String displayName = "Find handwritten Java source";
    String description = "Find Java files that are eligible for optional migration cleanups.";

    @Override
    public TreeVisitor<?, ExecutionContext> getVisitor() {
        return new JavaIsoVisitor<ExecutionContext>() {
            @Override
            public J.CompilationUnit visitCompilationUnit(J.CompilationUnit cu, ExecutionContext ctx) {
                return GeneratedJavaSource.isGeneratedSource(cu) ? cu : SearchResult.found(cu);
            }
        };
    }
}
